"""Regenerate secondlook/rungs/factcheckers.py from the IFCN signatory list.

The IFCN signatories page (https://ifcncodeofprinciples.poynter.org/signatories) loads its
list from the JSON endpoint below. Run this by hand, never in tests or at run time:

    python scripts/build_factchecker_domains.py > secondlook/rungs/factcheckers.py
"""
import json
import re
import sys
import urllib.request
from datetime import date
from urllib.parse import urlparse

PAGE = "https://ifcncodeofprinciples.poynter.org/signatories"
API = "https://ifcn-cop-prod-server-8q9x7.ondigitalocean.app/api/organization/signatories"
KEEP = ("Verified Signatory", "In Renewal")
PLATFORMS = ("facebook.com", "youtube.com", "twitter.com", "x.com", "instagram.com", "tiktok.com",
             "medium.com", "blogspot.com", "wordpress.com", "substack.com", "t.me")


def host_of(site: str) -> str:
    site = site.strip()
    if not re.match(r"^[a-z]+://", site, re.I):
        site = "http://" + site
    h = (urlparse(site).hostname or "").lower()
    return h[4:] if h.startswith("www.") else h


def main() -> None:
    with urllib.request.urlopen(API, timeout=60) as r:
        orgs = json.load(r)["organizations"]
    domains: dict[str, str] = {}
    for o in orgs:
        if o.get("signatory_status") not in KEEP or o.get("expired"):
            continue
        h = host_of((o.get("organization_owner") or {}).get("website") or "")
        if not h or "." not in h or any(h == p or h.endswith("." + p) for p in PLATFORMS):
            continue
        domains.setdefault(h, " ".join(o["name"].split()))
    print(f'''"""Sites of fact-checkers listed by the IFCN, used to label a claim card.

Source: the IFCN signatories page, {PAGE}, read {date.today().isoformat()} from the JSON
it loads ({API}).
Kept: organisations whose status on that list is "Verified Signatory" or "In Renewal".
"Expired Signatory" is left out. The site is the organisation's own `website` field, reduced
to its host. A host matches itself and its subdomains. Platforms (facebook.com and the like)
are never listed. Generated by scripts/build_factchecker_domains.py; do not edit by hand.

A site on this list is a site the IFCN lists for a fact-checking organisation. It does not
mean every page on it is a fact-check, and a fact-checker on another domain is simply not here.
"""
SOURCE = "{PAGE}"
READ_ON = "{date.today().isoformat()}"
STATUSES = {KEEP!r}
DOMAINS: dict[str, str] = {{''')
    for h in sorted(domains):
        print(f"    {h!r}: {domains[h]!r},")
    print("}")


if __name__ == "__main__":
    sys.exit(main())
